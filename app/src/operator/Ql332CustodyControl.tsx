import {useState} from 'react';
import {QL331_PUBLIC_SOURCES} from './ql331MasterAccess';
import {QL332_BOOTSTRAP_STEPS,QL332_PREFLIGHT,ql332ReleaseReadiness,ql332ReviewGate,
  type Ql332Check} from './ql332CustodyReadiness';
import './ql332-custody-control.css';

const readback=ql332ReleaseReadiness();
const help='https://github.com/RosevearCreations/rosevear-comms-hub/blob/main/docs/QL-332-MANAGED-CUSTODY-BOOTSTRAP-ROTATION.md';
export function Ql332CustodyControl({mode='it_command'}:{
  mode?:'it_command'|'management'|'analytics'|'system_status'
}){
  const [shellId,setShellId]=useState<string>('yw');
  const [check,setCheck]=useState<Ql332Check>('rotation');
  const [detailsOpen,setDetailsOpen]=useState(false);
  const selected=QL331_PUBLIC_SOURCES.find(item=>item.id===shellId)??QL331_PUBLIC_SOURCES[0];
  const gate=ql332ReviewGate(selected.id,check);
  const full=mode==='it_command';
  return <section className="ql332" data-ql332-state="key-custody-hold" aria-labelledby="ql332-heading">
    <header className="ql332-head">
      <div><p className="ql271-eyebrow">QL-332 · Managed Vault/KMS, peer issuer identity &amp; automated key rotation</p>
        <h3 id="ql332-heading">Private key custody control · locked until authentic trust bootstrap</h3>
        <p>Key handles, issuer fingerprints, rotation windows and receipt digests are separated from credentials. The public operator interface never sees key values or runs a peer handshake.</p></div>
      <span className="ql332-alert" role="status">KEY CUSTODY HOLD · 0 / 6 CONNECTED</span>
    </header>
    <div className="ql332-tiles">
      <article><small>Vault extension</small><strong>Installed</strong><span>Observed {QL332_PREFLIGHT.vaultExtensionObserved} · no approved live keys</span></article>
      <article><small>Verified private workloads</small><strong>{readback.enrolledWorkloads}</strong><span>No broker workload enrolled</span></article>
      <article><small>Original peer issuers</small><strong>{readback.pinnedVerifiedIssuers}</strong><span>Signed source Proof-B pending</span></article>
      <article><small>Key handles / rotations</small><strong>0 / 0</strong><span>No credential creation or rotation occurred</span></article>
    </div>
    <div className="ql332-note" role="note"><strong>Release boundary:</strong> This view shows a database-enforced private custody model and an isolated server-side rotation engine. It is not a live KMS deployment, connected source or owner-enrolled master. Supabase registry <code>{QL332_PREFLIGHT.selectedRegistry}</code>; counts are a dated preflight snapshot ({QL332_PREFLIGHT.observedDate}), not live secrets inventory.</div>
    {(full||mode==='system_status'||mode==='management')&&<section className="ql332-panel" aria-labelledby="ql332-check-heading">
      <h4 id="ql332-check-heading">Fail-closed key and issuer gate preview</h4>
      <p>Change the source and check to review a safe denial. No network request or database write is generated by these controls.</p>
      <div className="ql332-fields">
        <label htmlFor="ql332-source">Application shell or support
          <select id="ql332-source" value={selected.id} onChange={e=>setShellId(e.currentTarget.value)}>
            {QL331_PUBLIC_SOURCES.map(s=><option value={s.id} key={s.id}>{s.name}</option>)}
          </select></label>
        <label htmlFor="ql332-check">Security boundary
          <select id="ql332-check" value={check} onChange={e=>setCheck(e.currentTarget.value as Ql332Check)}>
            <option value="rotation">Due rotation / dual-key transition</option>
            <option value="fingerprint">Swapped or unverified issuer</option>
            <option value="source">Missing source-owned TEST authority</option>
            <option value="child">Child tenant permissions</option>
            <option value="emergency">Emergency private revocation</option>
          </select></label>
      </div>
      <div className="ql332-decision" role="status" aria-live="polite"><strong>{gate.verdict}</strong><p>{gate.detail}</p>
        <small>Key reads {gate.keyReads} · source calls {gate.sourceCalls} · new permissions {gate.permissionsAdded}</small></div>
    </section>}
    <section className="ql332-panel" aria-labelledby="ql332-bootstrap-heading">
      <h4 id="ql332-bootstrap-heading">Before autonomous managed rotation can start</h4>
      <button type="button" className="ql332-toggle" aria-expanded={detailsOpen} aria-controls="ql332-steps"
        onClick={()=>setDetailsOpen(open=>!open)}>{detailsOpen?'Hide':'Show'} six authentic key-custody gates</button>
      {detailsOpen&&<ol id="ql332-steps">{QL332_BOOTSTRAP_STEPS.map(step=><li key={step.id}>
        <strong>{step.label}</strong><span>{step.state}</span></li>)}</ol>}
      <p>Once genuine trust is established, the private coordinator can stage a version, verify both source and broker within a bounded dual-key overlap, atomically cut over and record nonsecret receipt hashes. Failures quarantine the scope; revoked or expired keys cannot silently reconnect.</p>
      <p><a href={help} target="_blank" rel="noopener noreferrer">Read QL-332 bootstrap, rotation, emergency recovery and verification instructions</a></p>
    </section>
    <footer>Provider selected: existing Supabase Vault, not yet authorized for peer secrets · Source calls 0 · Windows relay {QL332_PREFLIGHT.windowsRelay} · ACK {QL332_PREFLIGHT.ack}.</footer>
  </section>;
}
